std::string app::Ui(std::string_view text, bool caps) {
    int lang = Language();
    if (lang < 0) return std::string(text);

    // Dynamic per-language cache
    static std::mutex lock;
    static std::map<std::string, std::string> cache;
    std::lock_guard guard(lock);
    std::string key = std::to_string(lang) + "\t" + std::string(text) + (caps ? "\1" : "\2");
    if (auto it = cache.find(key); it != cache.end()) return it->second;

    std::string out;
    size_t i = 0;
    while (i < text.size()) {
        size_t end = 0;
        const char16_t* found = PhraseAt(text, i, end);
        if (!found) {
            out += text[i++];
            continue;
        }
        for (; *found; found++) AppendUtf8(out, caps ? Upper(*found) : *found);
        i = end;
    }

    if (lang == 5) {
        // Arabic contextual shaping and BiDi reordering for Dear ImGui LTR rendering
        out = arabic::ShapeAndBidi(out);
    }
    return cache[key] = out;
}

std::string app::FlashUi(std::string_view text, bool caps) {
    // Legacy Flash UI (Eurostile LT Std) and single-byte guest prompt buffers cannot display UTF-8 Arabic glyphs.
    if (Language() == 5) {
        return std::string(text);
    }
    return Ui(text, caps);
}
